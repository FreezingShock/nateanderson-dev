type Rows = readonly string[];
const flipX = (m: Rows): Rows => m.map((r) => [...r].reverse().join(""));
/** Rotate a 12 x 12 drawing a quarter turn counter-clockwise (right becomes up). */
const rotCCW = (m: Rows): Rows => Array.from({ length: SIZE }, (_, y) => Array.from({ length: SIZE }, (_, x) => m[x][SIZE - 1 - y]).join(""));

/** Mirrored and turned variants are derived, so they can never drift from the original drawing. */
const DERIVED = {
    chevR: flipX(MAPS.chevL),
    chevsR: flipX(MAPS.chevsL),
    arrowL: flipX(MAPS.arrowR),
    arrowUp: rotCCW(MAPS.arrowR),
} as const;

const ALL: Record<string, Rows> = { ...MAPS, ...DERIVED };

export type PixelName = keyof typeof MAPS | keyof typeof DERIVED;

/** Merge horizontal runs of pixels into single rects so each icon stays a handful of path segments. */
function build(rows: Rows) {
    const paths = { s: "", a: "", b: "" };
    const run = (key: "s" | "a" | "b", y: number, x0: number, x1: number) => {
        paths[key] += `M${x0} ${y}h${x1 - x0}v1h-${x1 - x0}z`;
    };
    rows.forEach((row, y) => {
        // Solid pixels merge into runs. Half-tone pixels never touch horizontally in a checkerboard, so each is one cell.
        let start = -1;
        for (let x = 0; x <= SIZE; x++) {
            const solid = x < SIZE && row[x] === "#";
            if (solid && start < 0) start = x;
            if (!solid && start >= 0) {
                run("s", y, start, x);
                start = -1;
            }
        }
        for (let x = 0; x < SIZE; x++) {
            if (row[x] !== ":") continue;
            run((x + y) % 2 === 0 ? "a" : "b", y, x, x + 1);
        }
    });
    return paths;
}

const BUILT = Object.fromEntries(Object.entries(ALL).map(([n, rows]) => [n, build(rows)])) as Record<PixelName, ReturnType<typeof build>>;

export type PixelIconProps = { name: PixelName; className?: string; style?: CSSProperties; size?: number };

/** Decorative by default (aria-hidden). The button or link that holds an icon carries the accessible label. */
export function PixelIcon({ name, className, style, size = 16 }: PixelIconProps) {
    const p = BUILT[name];
    return (
        <svg
            className={className ? `px ${className}` : "px"}
            data-ic={name}
            style={style}
            width={size}
            height={size}
            viewBox={`0 0 ${SIZE} ${SIZE}`}
            fill="currentColor"
            shapeRendering="crispEdges"
            aria-hidden="true"
            focusable="false"
        >
            <path className="px-s" d={p.s} />
            <path className="px-a" d={p.a} />
            <path className="px-b" d={p.b} />
        </svg>
    );
}

/** An icon as a component, for data files that store a component per entry (lucide-style props: className, style, size). */
export type PixelComponent = (props: { className?: string; style?: CSSProperties; size?: number; "aria-hidden"?: boolean | "true" | "false" }) => React.JSX.Element;
export function px(name: PixelName): PixelComponent {
    const C: PixelComponent = ({ className, style, size }) => <PixelIcon name={name} className={className} style={style} size={size} />;
    return C;
}

