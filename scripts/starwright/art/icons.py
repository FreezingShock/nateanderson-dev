ELS = [("h", "#5fb4ff"), ("he", "#ffc94d"), ("c", "#b4b9c4"), ("o", "#3fe0a0"), ("ne", "#ff5fc8"),
       ("mg", "#ff9a4d"), ("si", "#a98bff"), ("fe", "#e8e2d6"), ("au", "#ffd75e"), ("u", "#9dff6a")]


def shade(hx, k):
    c = np.array(hexc(hx), float)
    if k < 1:
        return tuple((c * k + np.array(hexc(P["ink"])) * (1 - k) * 0.6).astype(int))
    return tuple((c + (255 - c) * (k - 1)).astype(int))


def el_ramp(hx):
    return np.array([hexc(P["ink"]), shade(hx, 0.3), shade(hx, 0.6), shade(hx, 1.0), shade(hx, 1.45)], np.uint8)


def orb(v, cx, cy, r, x, y, amp=1.0):
    d = np.sqrt((x - cx) ** 2 + (y - cy) ** 2) / r
    lit = np.clip(1 - np.sqrt((x - cx + r * 0.4) ** 2 + (y - cy + r * 0.4) ** 2) / (r * 1.6), 0, 1)
    val = np.where(d < 1, 0.45 + 0.55 * lit, 0) * amp
    return np.maximum(v, val)


def el_tile(sym, col):
    s = 24
    x, y = grid(s, s)
    rp = el_ramp(col)
    v = np.zeros((s, s))
    cx = cy = 11.5
    if sym == "h":
        v = orb(v, cx, cy, 5.5, x, y)
        glow = np.clip(1 - np.sqrt((x - cx) ** 2 + (y - cy) ** 2) / 9, 0, 1) * 0.35
        v = np.maximum(v, glow)
    elif sym == "he":
        v = orb(v, cx - 3, cy + 1, 4, x, y); v = orb(v, cx + 3, cy - 1, 4, x, y)
    elif sym == "c":  # six-fold ring
        for i in range(6):
            a = i * math.pi / 3
            v = orb(v, cx + math.cos(a) * 6, cy + math.sin(a) * 6, 2.2, x, y)
        v = np.maximum(v, (np.abs(np.sqrt((x - cx) ** 2 + (y - cy) ** 2) - 6) < 0.6) * 0.35)
    elif sym == "o":  # nucleus with a tilted orbit
        v = orb(v, cx, cy, 3.6, x, y)
        e = np.sqrt(((x - cx) / 9) ** 2 + ((y - cy) / 4) ** 2)
        v = np.maximum(v, (np.abs(e - 1) < 0.11) * 0.55)
        v = orb(v, cx + 8.6, cy - 1.5, 1.5, x, y)
    elif sym == "ne":  # bent glass tube, lit
        path = np.zeros((s, s), bool)
        pts = [(5, 17), (5, 7), (11, 7), (11, 16), (18, 16), (18, 6)]
        for (ax, ay), (bx, by) in zip(pts, pts[1:]):
            for t in np.linspace(0, 1, 40):
                px, py = ax + (bx - ax) * t, ay + (by - ay) * t
                path |= (np.abs(x - px) <= 1) & (np.abs(y - py) <= 1)
        v = np.maximum(v, path * 0.95)
        halo = np.zeros((s, s))
        for py in range(s):
            for px in range(s):
                if path[py, px]:
                    halo[max(0, py - 2):py + 3, max(0, px - 2):px + 3] = 0.3
        v = np.maximum(v, halo)
    elif sym == "mg":  # a white-hot burning spark
        d = np.sqrt((x - cx) ** 2 + (y - cy) ** 2)
        a = np.arctan2(y - cy, x - cx)
        rays = np.abs(np.cos(a * 4)) ** 8 * np.clip(1 - d / 10, 0, 1)
        v = np.maximum(v, np.maximum(np.clip(1.15 - d / 4, 0, 1.2), rays))
    elif sym == "si":  # crystal shard
        sh = (np.abs(x - cx) * 1.8 + np.abs(y - cy) * 0.75 < 8.5)
        face = np.where(x < cx, 0.55, 0.95) * sh
        v = np.maximum(v, face)
        v = np.maximum(v, ((np.abs(x - cx) < 0.6) & sh) * 1.0)
    elif sym == "fe":  # iron block in three faces
        top = (y >= 6) & (y < 10) & (x - (10 - y) >= 4) & (x - (10 - y) < 15)
        front = (y >= 10) & (y < 19) & (x >= 4) & (x < 15)
        side = (x >= 15) & (x < 19) & (y >= 10 - (x - 15)) & (y < 19 - (x - 15))
        v = v + top * 0.95 + front * 0.62 + side * 0.4
    elif sym == "au":  # nugget with a glint
        n = np.sqrt(((x - cx) / 7.5) ** 2 + ((y - cy - 1) / 5.5) ** 2) + 0.15 * np.sin(x * 1.3) * np.cos(y)
        v = np.maximum(v, np.where(n < 1, 0.5 + 0.5 * np.clip(1 - n, 0, 1) + (x < cx) * 0.1, 0))
        g = ((np.abs(x - 8) < 0.6) & (np.abs(y - 9) < 2.6)) | ((np.abs(y - 9) < 0.6) & (np.abs(x - 8) < 2.6))
        v = np.where(g, 1.0, v)
    elif sym == "u":  # glowing rod with three hazard blades
        d = np.sqrt((x - cx) ** 2 + (y - cy) ** 2)
        a = (np.arctan2(y - cy, x - cx) + math.pi / 2) % (2 * math.pi / 3)
        blades = (d > 3.2) & (d < 8.5) & (a < math.pi / 3)
        v = np.maximum(v, blades * 0.8)
        v = np.maximum(v, (d < 2.2) * 1.0)
        v = np.maximum(v, ((d > 8.5) & (d < 10)) * 0.25)
    img = pick(rp, np.clip(v, 0, 1))
    # frame: dark tile, edge in the element colour, one lit corner (top left)
    frame = (x == 0) | (y == 0) | (x == s - 1) | (y == s - 1)
    bg = (v <= 0.02) & ~frame
    img[bg] = pick(np.array([hexc(P["void"]), hexc(P["ink"]), shade(col, 0.22)], np.uint8), np.clip((1 - (x + y) / 46) * 0.7, 0, 1))[bg]
    img[frame] = shade(col, 0.45)
    corner = ((x <= 4) & (y == 0)) | ((y <= 4) & (x == 0))
    img[corner] = shade(col, 1.35)
    img[(x == s - 1) | (y == s - 1)] = shade(col, 0.28)
    return rgba(img, np.ones((s, s), bool))


