def bitmap(art, names):
    rows = [r for r in art.strip("\n").split("\n")]
    h, w = len(rows), max(len(r) for r in rows)
    img = np.zeros((h, w, 4), np.uint8)
    pal = [hexc(P[n]) for n in names]
    for yy, row in enumerate(rows):
        for xx, ch in enumerate(row):
            if ch == ".":
                continue
            i = min("abcde".index(ch), len(pal) - 1)
            img[yy, xx, :3] = pal[i]
            img[yy, xx, 3] = 255
    return img


def panel():
    # corner bracket cell (top-left orientation; the GUI flips it for the other corners)
    c = np.zeros((8, 8, 4), np.uint8)
    for i in range(8):
        for (yy, xx) in ((0, i), (i, 0)):
            c[yy, xx] = (*hexc(P["amber"] if i < 5 else P["rust"]), 255)
    for i in range(1, 4):
        c[1, i] = (*hexc(P["ember1"]), 255); c[i, 1] = (*hexc(P["ember1"]), 255)
    save_still("panel/corner", c)
    th = thresh(4, 8)
    rule = np.zeros((4, 8, 4), np.uint8)
    on = th < np.array([[0.1], [0.55], [0.55], [0.1]])
    rule[on] = (*hexc(P["dusk"]), 255)
    rule[1:3][th[1:3] < 0.25] = (*hexc(P["plum"]), 255)
    save_still("panel/rule", rule)
    bar = np.zeros((4, 8, 4), np.uint8)
    bar[..., 3] = 255
    bar[..., :3] = pick(R("rust", "flame", "amber", "gold"), np.array([[0.95] * 8, [0.7] * 8, [0.55] * 8, [0.3] * 8]))
    save_still("panel/bar", bar)
    y = np.linspace(1, 0, 64)[:, None] * np.ones((64, 4))
    top = rgba(np.zeros((64, 4, 3), np.uint8), dmask(y ** 1.4))
    save_still("panel/vignette-top", top)
    save_still("panel/vignette-bottom", top[::-1].copy())


def run():
    for sym, col in ELS:
        save_still(f"icon/el-{sym}", el_tile(sym, col))
    for k, (art, names) in ICON.items():
        save_still(f"icon/{k}", bitmap(art, names))
    panel()
