"""Brasswork UI icon sheet: menu, panel and stage-button glyphs at 64 px, 8 per row, same grid as items.png.

  public/brasswork/icons/ui.{png,webp}   8 columns, 64 px cells, in ORDER below (new glyphs go at the end)
  lib/automation/icons/ui.ts              generated index (cell per id, content-hash ?v= stamp, uiIconStyle helper)

Art: scripts/brasswork/bw_ui.py. Run: python3 scripts/brasswork/build-ui-icons.py [--preview out.png]
"""
import hashlib
import sys
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw, ImageFont

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(HERE))
import bw_ui  # noqa: E402
from nodefarm_icon_kit import save_pair, to_image  # noqa: E402

COLS, N = 8, 64
OUT = ROOT / "public/brasswork/icons"
TS = ROOT / "lib/automation/icons/ui.ts"

# Cell order is part of the public index: append new glyphs, never reorder.
ORDER = [
    ("research", "Research"), ("expedition", "Expedition"), ("stats", "Production stats"), ("settings", "Settings"),
    ("milestones", "Milestones"), ("prestige", "Prestige / new workshop"), ("machines", "Machines"), ("photo", "Photo"),
    ("light", "Light"), ("codex", "Codex"), ("keys", "Keys"), ("power", "Power"),
    ("logistics", "Logistics"), ("blueprints", "Blueprints"), ("sound", "Sound"), ("rates", "Rates"),
    ("undo", "Undo"), ("redo", "Redo"), ("remove", "Remove"), ("map", "Map"),
    ("hammer", "Build"), ("rotate", "Rotate"), ("time", "Time / day"), ("pause", "Pause"),
    ("play", "Play"), ("fast", "Fast forward"), ("help", "Help"), ("info", "Info"),
]


def main():
    ids = [i for i, _ in ORDER]
    missing = [i for i in ids if i not in bw_ui.UI]
    if missing:
        sys.exit(f"no drawing for: {', '.join(missing)}")
    rows = (len(ids) + COLS - 1) // COLS
    sheet = np.zeros((rows * N, COLS * N, 4), np.uint8)
    for k, i in enumerate(ids):
        r, c = divmod(k, COLS)
        sheet[r * N:(r + 1) * N, c * N:(c + 1) * N] = bw_ui.UI[i]().img
    img = to_image(sheet)
    save_pair(img, OUT / "ui")
    v = hashlib.sha1((OUT / "ui.webp").read_bytes()).hexdigest()[:8]
    q = lambda k: k if k.isidentifier() else f'"{k}"'  # noqa: E731
    cells = ",\n".join(f"    {q(i)}: {k}, // {name}" for k, (i, name) in enumerate(ORDER))
    TS.write_text(f'''// Generated by scripts/brasswork/build-ui-icons.py. Do not edit; re-run the script after changing the art.
import type {{ CSSProperties }} from "react";

/** HUD glyph sheet (menus, panel headers, stage buttons): 64 px art cells, {COLS} across, row by row. */
export const UI_ICON_SHEET = {{
    url: "/brasswork/icons/ui.webp?v={v}",
    png: "/brasswork/icons/ui.png?v={v}",
    cell: {N},
    cols: {COLS},
    rows: {rows},
}} as const;

/** Sheet cell of each HUD glyph. Cell order is stable: new glyphs are appended. */
export const UI_ICONS = {{
{cells}
}} as const;

export type UiIconId = keyof typeof UI_ICONS;

/** Sheet cell for a HUD glyph id, or undefined if there is none. */
export function uiIconCell(id: string): number | undefined {{
    return (UI_ICONS as Record<string, number>)[id];
}}

/**
 * Inline style that shows one HUD glyph as a background at `px` CSS pixels (24 on buttons, 32 on panel headers). Same
 * shape as iconStyle() in ./index, so the two are interchangeable; drawn with bold strokes so 24 px stays readable.
 */
export function uiIconStyle(id: UiIconId | string, px = 24): CSSProperties {{
    const k = uiIconCell(id) ?? 0;
    const col = k % UI_ICON_SHEET.cols;
    const row = Math.floor(k / UI_ICON_SHEET.cols);
    return {{
        width: px,
        height: px,
        backgroundImage: `url(${{UI_ICON_SHEET.url}})`,
        backgroundRepeat: "no-repeat",
        backgroundSize: `${{UI_ICON_SHEET.cols * px}}px ${{UI_ICON_SHEET.rows * px}}px`,
        backgroundPosition: `${{-col * px}}px ${{-row * px}}px`,
        imageRendering: px >= 32 ? "pixelated" : "auto",
    }};
}}
''')
    print(f"ui: {img.size}, webp {(OUT / 'ui.webp').stat().st_size / 1024:.1f} KB, {len(ids)} glyphs, v={v}")
    if "--preview" in sys.argv:
        preview(sheet, sys.argv[sys.argv.index("--preview") + 1])


def preview(sheet, path):
    """Each glyph at 2x with its name, then at 32 and 24 px on a dark panel and on a brass button."""
    bg, ink, dim, brass = (24, 19, 14), (240, 223, 184), (150, 128, 96), (210, 154, 60)
    f = ImageFont.truetype("/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf", 12)
    fb = ImageFont.truetype("/usr/share/fonts/truetype/dejavu/DejaVuSansMono-Bold.ttf", 15)
    cw, ch, cols, PAD = 190, 160, 7, 20
    rows = (len(ORDER) + cols - 1) // cols
    W, H = max(PAD * 2 + cols * cw, PAD + 170 + len(ORDER) * 34), 50 + rows * ch + 40
    out = Image.new("RGBA", (W, H), bg + (255,))
    d = ImageDraw.Draw(out)
    d.text((PAD, 14), "BRASSWORK  HUD glyphs   64 px art at 2x, then 32 px and 24 px", font=fb, fill=brass)
    for k, (i, name) in enumerate(ORDER):
        r, c = divmod(k, COLS)
        cell = to_image(sheet[r * N:(r + 1) * N, c * N:(c + 1) * N])
        x0, y0 = PAD + (k % cols) * cw, 50 + (k // cols) * ch
        d.rectangle((x0 - 2, y0 - 2, x0 + 129, y0 + 129), fill=(40, 31, 22))
        out.alpha_composite(cell.resize((128, 128), Image.NEAREST), (x0, y0))
        d.text((x0, y0 + 132), name, font=f, fill=ink)
        for j, px in enumerate((32, 24)):
            y = y0 + 8 + j * 44
            d.rectangle((x0 + 133 - 2 - 2, y - 4, x0 + 133 + px + 2, y + px + 4), fill=(52, 40, 28), outline=(110, 82, 40))
            out.alpha_composite(cell.resize((px, px), Image.LANCZOS), (x0 + 131, y))
    # a mock toolbar at 24 px, as it would sit on the HUD
    y = 50 + rows * ch
    d.text((PAD, y - 6), "toolbar at 24 px:", font=f, fill=dim)
    x = PAD + 150
    for k, (i, _) in enumerate(ORDER):
        r, c = divmod(k, COLS)
        cell = to_image(sheet[r * N:(r + 1) * N, c * N:(c + 1) * N]).resize((24, 24), Image.LANCZOS)
        d.rectangle((x - 3, y - 9, x + 26, y + 20), fill=(58, 44, 28), outline=(140, 104, 48))
        out.alpha_composite(cell, (x, y - 6))
        x += 34
    out.convert("RGB").save(path)
    print("preview:", path)


if __name__ == "__main__":
    main()
