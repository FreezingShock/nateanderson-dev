"""Build Groundbreak job strips and backdrop layers.

  public/groundbreak/jobs/<job>.webp      one horizontal strip per job, frames side by side (no gaps)
  public/groundbreak/backdrop/<layer>.webp
  components/groundbreak-art/scene-data.ts  generated: frame names, sizes, ?v= stamps

Run: python3 scripts/groundbreak-art/build-scene.py
"""
import hashlib
import json
import sys
from pathlib import Path

import numpy as np
from PIL import Image

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(HERE))
import gb_backdrop  # noqa: E402
import gb_buildings  # noqa: E402


PUB = ROOT / "public/groundbreak"
TS = ROOT / "components/groundbreak-art/scene-data.ts"


def stamp(img):
    return hashlib.sha1(img.tobytes()).hexdigest()[:8]


def clear_soil(c, lot, ug):
    """Leave only what the job did to the ground: underground pixels that still match the untouched lot are cleared, so
    the shore's own soil runs straight through the site with no seam, and only the pit, piles and footings show."""
    gy = c.h - ug + 2
    same = (c.img[gy:] == lot[gy:]).all(-1)
    c.img[gy:][same, 3] = 0


def main():
    (PUB / "jobs").mkdir(parents=True, exist_ok=True)
    (PUB / "backdrop").mkdir(parents=True, exist_ok=True)
    jobs = {}
    for key, (name, frames, cs) in gb_buildings.build_all().items():
        w, h = cs[0].w, cs[0].h
        strip = Image.new("RGBA", (w * len(cs), h))
        lot = cs[0].img.copy()
        for i, c in enumerate(cs):
            clear_soil(c, lot, gb_buildings.UG)
            strip.alpha_composite(c.image(), (i * w, 0))
        strip.save(PUB / "jobs" / f"{key}.webp", lossless=True, quality=100, method=6)
        jobs[key] = {"name": name, "frames": frames, "w": w, "h": h, "ground": gb_buildings.UG,
                     "src": f"/groundbreak/jobs/{key}.webp?v={stamp(strip)}"}
    layers = {}
    for key, c in gb_backdrop.all_layers().items():
        img = c.image()
        img.save(PUB / "backdrop" / f"{key}.webp", lossless=True, quality=100, method=6)
        layers[key] = f"/groundbreak/backdrop/{key}.webp?v={stamp(img)}"
    TS.parent.mkdir(parents=True, exist_ok=True)
    TS.write_text(
        "// Generated by scripts/groundbreak-art/build-scene.py. Do not edit by hand.\n"
        f"export const GB_BACKDROP = {{ w: {gb_backdrop.W}, h: {gb_backdrop.H}, horizon: {gb_backdrop.HORIZON}, "
        f"siteY: {gb_backdrop.HORIZON + 120}, layers: {json.dumps(layers, indent=2)} }} as const;\n\n"
        f"export const GB_JOBS = {json.dumps(jobs, indent=2)} as const;\n\n"
        "export type GbJobId = keyof typeof GB_JOBS;\n"
        "export const GB_JOB_ORDER = Object.keys(GB_JOBS) as GbJobId[];\n")
    print(len(jobs), "jobs,", len(layers), "layers")


main()
