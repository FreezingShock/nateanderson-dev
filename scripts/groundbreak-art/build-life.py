"""Build Groundbreak site-life sheets (crew, vehicles, effects) and the job outline data the scene uses to place them.

  public/groundbreak/life/{crew,vehicles,fx}.png
  components/groundbreak-art/life-data.ts   generated: frame grids, ?v= stamps, per-job-frame roof line and footprint

Run: python3 scripts/groundbreak-art/build-life.py [--preview out.png]
"""
import hashlib
import json
import sys
from pathlib import Path

import numpy as np
from PIL import Image

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(HERE))
import gb_life as L  # noqa: E402

OUT = ROOT / "public/groundbreak/life"
TS = ROOT / "components/groundbreak-art/life-data.ts"
SCENE = ROOT / "components/groundbreak-art/scene-data.ts"


def stamp(img):
    return hashlib.sha1(img.tobytes()).hexdigest()[:8]


def job_outlines():
    """For every job strip frame: the roof line (topmost row the building fills across a fifth of the lot, so a crane mast
    or a flag pole does not count) and the left/right edge of the build at ground level, in frame pixels."""
    txt = SCENE.read_text()
    data = json.loads(txt[txt.index("export const GB_JOBS = ") + 23: txt.rindex("} as const") + 1])
    out = {}
    for jid, j in data.items():
        im = np.asarray(Image.open(ROOT / "public" / j["src"].split("?")[0].lstrip("/")).convert("RGBA"))
        w, h, g = j["w"], j["h"], j["ground"]
        gy = h - g
        frames = []
        for i in range(len(j["frames"])):
            fr = im[:gy, i * w:(i + 1) * w].astype(int)
            crane = ((fr[..., 0] > 120) & (fr[..., 0] - fr[..., 2] > 90) & (fr[..., 1] > 60)) | (fr[..., :3].sum(-1) < 60)  # hi-vis crane, beacons, cones
            a = (fr[..., 3] > 128) & ~crane
            mid = a[:, int(w * 0.1):int(w * 0.9)]
            rows = mid.sum(1)
            filled = np.where(rows >= w * 0.22)[0]
            top = int(filled[0]) if len(filled) else gy
            near = a[max(0, gy - 6):gy].any(0)
            xs = np.where(a[top:gy].mean(0) >= 0.3)[0] if top < gy - 2 else []
            l, r = (int(xs[0]), int(xs[-1])) if len(xs) else (int(w * 0.3), int(w * 0.7))
            # floor lines: rows where a beam or slab spans most of the build, one per cluster (its top row)
            floors = []
            if r - l > 20:
                span = a[:gy, l:r + 1].sum(1) >= (r - l) * 0.7
                for y in range(top, gy - 6):
                    if span[y] and not span[y - 1] and (not floors or y - floors[-1] >= 12):
                        floors.append(y)
            frames.append([top - gy, l, r, [f - gy for f in floors if f - gy < -10]])  # offsets from the ground line
        out[jid] = frames
    return out


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    sheets = {"crew": L.crew_sheet(), "mini": L.mini_sheet(), "vehicles": L.vehicle_sheet(), "machines": L.machine_sheet(), "fx": L.fx_sheet()}
    climb, lad, mast, cages = L.vertical_sheet()
    sheets.update({"climb": climb, "ladder": lad, "mast": mast, "cage": cages})
    stamps = {}
    for k, c in sheets.items():
        im = c.image()
        im.save(OUT / f"{k}.png", optimize=True)
        stamps[k] = stamp(im)
    def cols(spec):
        out, col = {}, 0
        for a, n in spec:
            out[a] = [col, n]
            col += n
        return out
    actions = cols(L.CREW_ACTIONS)
    data = {
        "gutter": L.G,
        "crew": {"src": f"/groundbreak/life/crew.png?v={stamps['crew']}", "w": L.CW, "h": L.CH, "foot": L.FOOT,
                 "variants": len(L.CREW_VARIANTS), "actions": actions},
        "mini": {"src": f"/groundbreak/life/mini.png?v={stamps['mini']}", "w": L.MW, "h": L.MH, "foot": L.MFOOT,
                 "actions": cols(L.MINI_ACTIONS)},
        "machines": {"src": f"/groundbreak/life/machines.png?v={stamps['machines']}", "w": L.XW, "h": L.XH, "ground": L.XG,
                     "rows": {k: i for i, k in enumerate(L.MACHINE_ROWS)}},
        "climb": {"src": f"/groundbreak/life/climb.png?v={stamps['climb']}", "w": L.MW, "h": L.MH},
        "ladder": {"src": f"/groundbreak/life/ladder.png?v={stamps['ladder']}", "w": L.LW, "h": L.LH},
        "mast": {"src": f"/groundbreak/life/mast.png?v={stamps['mast']}", "w": L.HW, "h": L.HH},
        "cage": {"src": f"/groundbreak/life/cage.png?v={stamps['cage']}", "w": L.CW2, "h": L.CH2},
        "vehicles": {"src": f"/groundbreak/life/vehicles.png?v={stamps['vehicles']}", "w": L.VW, "h": L.VH,
                     "rows": {"dump": 0, "mixer": 1, **{f"flat-{c}": 2 + i for i, c in enumerate(L.CARGO)}}},
        "fx": {"src": f"/groundbreak/life/fx.png?v={stamps['fx']}", "w": L.FW, "h": L.FH,
               "rows": {"dust": [0, 6], "grit": [1, 6], "sparks": [2, 4], "burst": [3, 8]}},
        "outline": job_outlines(),
    }
    TS.write_text("// Generated by scripts/groundbreak-art/build-life.py. Do not edit by hand.\n"
                  f"export const GB_LIFE = {json.dumps(data, indent=2)} as const;\n")
    if "--preview" in sys.argv:
        dst = sys.argv[sys.argv.index("--preview") + 1]
        ims = [sheets[k].image() for k in sheets]
        W = max(i.width for i in ims)
        canvas = Image.new("RGBA", (W, sum(i.height + 8 for i in ims)), (40, 30, 50, 255))
        y = 0
        for i in ims:
            canvas.alpha_composite(i, (0, y))
            y += i.height + 8
        canvas.resize((canvas.width * 3, canvas.height * 3), Image.NEAREST).save(dst)
    print("ok", stamps)


if __name__ == "__main__":
    main()
