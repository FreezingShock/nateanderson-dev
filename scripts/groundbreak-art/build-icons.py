"""Build the Groundbreak icon sheet.

  public/groundbreak/icons/icons.{png,webp}   8 columns, 64 px cells, ids in gb_icons.ORDER
  components/groundbreak-art/icons.ts         generated index (cell per id, ?v= content stamp)

Run: python3 scripts/groundbreak-art/build-icons.py [--preview out.png]
"""
import hashlib
import sys
from pathlib import Path

from PIL import Image, ImageDraw

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(HERE))
import gb_icons  # noqa: E402
from gb_kit import save_pair  # noqa: E402

COLS, N = 8, 64
OUT = ROOT / "public/groundbreak/icons"
TS = ROOT / "components/groundbreak-art/icons.ts"


def main():
    ids = gb_icons.ORDER
    rows = (len(ids) + COLS - 1) // COLS
    sheet = Image.new("RGBA", (COLS * N, rows * N), (0, 0, 0, 0))
    for i, k in enumerate(ids):
        sheet.alpha_composite(gb_icons.render(k).image(), ((i % COLS) * N, (i // COLS) * N))
    OUT.mkdir(parents=True, exist_ok=True)
    sheet.save(OUT / "icons.webp", lossless=True, quality=100, method=6)
    single = {}
    for i, k in enumerate(ids):
        im = sheet.crop(((i % COLS) * N, (i // COLS) * N, (i % COLS + 1) * N, (i // COLS + 1) * N))
        im.save(OUT / f"{k}.png", optimize=True)
        single[k] = hashlib.sha1(im.tobytes()).hexdigest()[:8]
    v = hashlib.sha1(sheet.tobytes()).hexdigest()[:8]
    lines = [
        "// Generated by scripts/groundbreak-art/build-icons.py. Do not edit by hand.",
        f'export const GB_ICON_SHEET = "/groundbreak/icons/icons.webp?v={v}";',
        f"export const GB_ICON_COLS = {COLS};",
        f"export const GB_ICON_ROWS = {rows};",
        "export const GB_ICON_CELL = 64;",
        "export const GB_ICONS = {",
        *[f"  {k}: {i}," for i, k in enumerate(ids)],
        "} as const;",
        "export type GbIconId = keyof typeof GB_ICONS;",
        "const V: Record<string, string> = {",
        *[f'  {k}: "{single[k]}",' for k in ids],
        "};",
        "/** URL of one icon as its own 64 px PNG (show it with image-rendering: pixelated). */",
        "export function gbIconUrl(id: string): string | null {",
        "  return V[id] ? `/groundbreak/icons/${id}.png?v=${V[id]}` : null;",
        "}",
        "",
    ]
    TS.parent.mkdir(parents=True, exist_ok=True)
    TS.write_text("\n".join(lines))
    if "--preview" in sys.argv:
        out = sys.argv[sys.argv.index("--preview") + 1]
        sc = 3
        pv = Image.new("RGBA", (COLS * (N * sc + 24) + 24, rows * (N * sc + 46) + 24), (20, 16, 24, 255))
        d = ImageDraw.Draw(pv)
        for i, k in enumerate(ids):
            x, y = 24 + (i % COLS) * (N * sc + 24), 24 + (i // COLS) * (N * sc + 46)
            d.rectangle([x - 2, y - 2, x + N * sc + 1, y + N * sc + 1], fill=(30, 25, 34, 255))
            pv.alpha_composite(gb_icons.render(k).image().resize((N * sc, N * sc), Image.NEAREST), (x, y))
            d.text((x, y + N * sc + 8), k, fill=(240, 200, 140, 255))
        pv.save(out)
    print(f"{len(ids)} icons, v={v}")


main()
